package com.research.pubmanager;

/**
 * Standard workaround entry point for JavaFX 11+ applications.
 * Running this class avoids the common "Error: JavaFX runtime components are missing"
 * when launched directly from IntelliJ IDEA without module-path CLI arguments.
 */
public class Launcher {
    public static void main(String[] args) {
        MainApp.main(args);
    }
}
